def label(tid):
    """返回 'T1059.001 PowerShell' 形式的短标签。"""
    if not tid:
        return ""
    t = TECHNIQUES.get(tid)
    return ("%s %s" % (tid, t[1])) if t else str(tid)


def tactic(tid):
    t = TECHNIQUES.get(tid)
    return t[0] if t else "未分类"


def summary():
    """给前端做覆盖图：按战术聚合已支持的技术数。"""
    out = {}
    for tid, (tac, name) in TECHNIQUES.items():
        out.setdefault(tac, []).append({"id": tid, "name": name})
    return [{"tactic": t, "techniques": out[t]} for t in TACTIC_ORDER if t in out]
